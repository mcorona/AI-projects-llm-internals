"""Semana 13, actividad 6: agente contra workflow, por tipo de tarea (resultados/agente_vs_workflow.md).

Mismo golden set, mismo k = 3, mismo modelo (Haiku 5.5 low) y la misma verificación por ejecución. Para cada tipo:
pass@1, pass^3, costo y latencia por tarea (p50 / p95) y la diferencia de pass@1 agente − workflow con bootstrap
pareado por tarea (IC 95 %).

    python workflow/comparar.py --agente eval_haiku_low --workflow workflow_s10
"""
import argparse
import json
import random
import statistics
import sys
from collections import Counter, defaultdict
from pathlib import Path

AQUI = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(AQUI))
from agente.evaluar import TIPOS, p  # noqa: E402

RES = AQUI / "resultados"


def cargar(corrida):
    filas = [json.loads(x) for x in open(RES / f"{corrida}_detalle.jsonl", encoding="utf-8")]
    por = defaultdict(list)
    for f in filas:
        por[f["id"]].append(f)
    return filas, por


def boot_dif(a, b, ids, n=2000, semilla=13):
    rnd = random.Random(semilla)
    d = lambda s: statistics.mean(statistics.mean(x["exito"] for x in a[i]) - statistics.mean(x["exito"] for x in b[i]) for i in s)  # noqa: E731
    vals = sorted(d([rnd.choice(ids) for _ in ids]) for _ in range(n))
    return d(ids), (vals[int(0.025 * n)], vals[int(0.975 * n) - 1])


def resumen(filas, por, ids):
    sub = [f for f in filas if f["id"] in ids]
    k = max(f["rep"] for f in sub) + 1
    return {"pass1": statistics.mean(statistics.mean(x["exito"] for x in por[i]) for i in ids),
            "passk": statistics.mean(all(x["exito"] for x in por[i]) and len(por[i]) == k for i in ids),
            "usd": (p([f["costo_usd"] for f in sub], .5), p([f["costo_usd"] for f in sub], .95)),
            "seg": (p([f["segundos"] for f in sub], .5), p([f["segundos"] for f in sub], .95)),
            "pasos": (p([f["pasos"] for f in sub], .5), p([f["pasos"] for f in sub], .95)),
            "costo_total": sum(f["costo_usd"] for f in sub)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--agente", default="eval_haiku_low")
    ap.add_argument("--workflow", default="workflow_s10")
    a = ap.parse_args()
    fa, pa = cargar(a.agente)
    fw, pw = cargar(a.workflow)
    tipo = {f["id"]: f["tipo"] for f in fa}
    comunes = sorted(set(pa) & set(pw))
    out = {"tareas": len(comunes), "por_tipo": {}, "rutas_workflow": dict(Counter(f"{f['tipo']}: {f['ruta']}" for f in fw).most_common())}
    filas_md = []
    for t in TIPOS + ["total"]:
        ids = [i for i in comunes if t == "total" or tipo[i] == t]
        ra, rw = resumen(fa, pa, ids), resumen(fw, pw, ids)
        dif, ic = boot_dif(pa, pw, ids)
        out["por_tipo"][t] = {"tareas": len(ids), "agente": ra, "workflow": rw, "dif_pass1": dif, "ic": ic}
        nombre = "**Total**" if t == "total" else t
        filas_md.append(f"| {nombre} | {len(ids)} | {ra['pass1']:.3f} / {ra['passk']:.3f} | {rw['pass1']:.3f} / {rw['passk']:.3f} | "
                        f"**{dif:+.3f}** [{ic[0]:+.3f}, {ic[1]:+.3f}] | ${ra['usd'][0]:.4f} / ${ra['usd'][1]:.4f} | "
                        f"${rw['usd'][0]:.4f} / ${rw['usd'][1]:.4f} | {ra['seg'][0]:.1f} / {ra['seg'][1]:.1f} | {rw['seg'][0]:.1f} / {rw['seg'][1]:.1f} |")
    fallos_w = Counter(f["id"] for f in fw if not f["exito"])
    md = ["# Activity 6: agent vs workflow", "",
          f"Generated by [`workflow/comparar.py`](../workflow/comparar.py). Same gold set ({len(comunes)} tasks), k = 3, Haiku 5.5 `low`, "
          "same execution-based verification. Agent: the own agentic loop (activity 3, run in activity 5). Workflow: the "
          "week 10 assistant with fixed routing ([`workflow/semana10.py`](../workflow/semana10.py)). 95 % CI by paired bootstrap over tasks.", "",
          "| Task type | Tasks | Agent pass@1 / pass^3 | Workflow pass@1 / pass^3 | Agent − workflow pass@1 [95 % CI] | "
          "Agent USD p50 / p95 | Workflow USD p50 / p95 | Agent s p50 / p95 | Workflow s p50 / p95 |",
          "|---|---|---|---|---|---|---|---|---|", *filas_md, "",
          f"Total cost: agent ${out['por_tipo']['total']['agente']['costo_total']:.2f}, workflow ${out['por_tipo']['total']['workflow']['costo_total']:.2f} "
          f"({len(fw)} workflow runs).", "",
          "Workflow routes (task type: route, over all runs): " + ", ".join(f"{k} ×{v}" for k, v in out["rutas_workflow"].items()) + ".", "",
          "Workflow failed runs: " + (", ".join(f"{i} ({n}/3)" for i, n in sorted(fallos_w.items())) or "none") + "."]
    (RES / "agente_vs_workflow.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    (RES / "agente_vs_workflow.json").write_text(json.dumps(out, ensure_ascii=False, indent=1, default=str) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
