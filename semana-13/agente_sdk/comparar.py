"""Semana 13, actividad 10: los tres patrones sobre el mismo golden set (resultados/patrones.md).

Workflow de semana 10 (ruteo fijo), agente con loop propio y agente con Claude Agent SDK; mismo golden set (84 tareas),
k = 3, Haiku 5.5 low y la misma verificación por ejecución. Por tipo de tarea: pass@1 / pass^3, costo y latencia p50,
y las diferencias SDK − loop propio y SDK − workflow con bootstrap pareado por tarea (IC 95 %).

    python agente_sdk/comparar.py --loop eval_haiku_low --sdk eval_sdk_low --workflow workflow_s10
"""
import argparse
import json
import sys
from pathlib import Path

AQUI = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(AQUI))
from agente.evaluar import TIPOS  # noqa: E402
from workflow.comparar import boot_dif, cargar, resumen  # noqa: E402

RES = AQUI / "resultados"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--loop", default="eval_haiku_low")
    ap.add_argument("--sdk", default="eval_sdk_low")
    ap.add_argument("--workflow", default="workflow_s10")
    a = ap.parse_args()
    (fl, pl), (fs, ps), (fw, pw) = cargar(a.loop), cargar(a.sdk), cargar(a.workflow)
    tipo = {f["id"]: f["tipo"] for f in fl}
    comunes = sorted(set(pl) & set(ps) & set(pw))
    out, filas = {"tareas": len(comunes), "por_tipo": {}}, []
    for t in TIPOS + ["total"]:
        ids = [i for i in comunes if t == "total" or tipo[i] == t]
        rl, rs, rw = resumen(fl, pl, ids), resumen(fs, ps, ids), resumen(fw, pw, ids)
        d_sl, ic_sl = boot_dif(ps, pl, ids)
        d_sw, ic_sw = boot_dif(ps, pw, ids)
        out["por_tipo"][t] = {"tareas": len(ids), "loop": rl, "sdk": rs, "workflow": rw, "sdk_menos_loop": [d_sl, ic_sl],
                              "sdk_menos_workflow": [d_sw, ic_sw]}
        n = "**Total**" if t == "total" else t
        filas.append(f"| {n} | {len(ids)} | {rw['pass1']:.3f} / {rw['passk']:.3f} | {rl['pass1']:.3f} / {rl['passk']:.3f} | "
                     f"{rs['pass1']:.3f} / {rs['passk']:.3f} | {d_sl:+.3f} [{ic_sl[0]:+.3f}, {ic_sl[1]:+.3f}] | "
                     f"{d_sw:+.3f} [{ic_sw[0]:+.3f}, {ic_sw[1]:+.3f}] | ${rw['usd'][0]:.4f} / ${rl['usd'][0]:.4f} / ${rs['usd'][0]:.4f} | "
                     f"{rw['seg'][0]:.1f} / {rl['seg'][0]:.1f} / {rs['seg'][0]:.1f} |")
    tot = out["por_tipo"]["total"]
    md = ["# Activity 10: three patterns on the same gold set", "",
          f"Generated by [`agente_sdk/comparar.py`](../agente_sdk/comparar.py). {len(comunes)} tasks, k = 3, Haiku 5.5 `low`, same "
          "execution-based verification. Workflow: week 10 assistant with fixed routing. Own loop: activity 3. Agent SDK: "
          "activity 10, same tools, prompt and limits. 95 % CI by paired bootstrap over tasks.", "",
          "| Task type | Tasks | Workflow pass@1 / pass^3 | Own loop pass@1 / pass^3 | Agent SDK pass@1 / pass^3 | SDK − own loop [95 % CI] | "
          "SDK − workflow [95 % CI] | USD p50 (workflow / loop / SDK) | Seconds p50 (workflow / loop / SDK) |",
          "|---|---|---|---|---|---|---|---|---|", *filas, "",
          f"Total cost for 252 runs: workflow ${tot['workflow']['costo_total']:.2f}, own loop ${tot['loop']['costo_total']:.2f}, "
          f"Agent SDK ${tot['sdk']['costo_total']:.2f}. p95 seconds: workflow {tot['workflow']['seg'][1]:.1f}, own loop "
          f"{tot['loop']['seg'][1]:.1f}, Agent SDK {tot['sdk']['seg'][1]:.1f}."]
    (RES / "patrones.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    (RES / "patrones.json").write_text(json.dumps(out, ensure_ascii=False, indent=1, default=str) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
